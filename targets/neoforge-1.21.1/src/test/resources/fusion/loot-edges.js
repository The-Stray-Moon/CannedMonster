var totals = {};
for (var entity of world.getAllEntities()) {
    if (String(AutoJS.id(entity.getType())) !== 'minecraft:item') continue;
    var stack = entity.getItem();
    var id = String(AutoJS.id(stack.getItem()));
    totals[id] = (totals[id] || 0) + stack.getCount();
}
check(totals['minecraft:diamond'] === 24, 'canceled event produced no equipment in world');
check(totals['minecraft:red_wool'] === 3, 'canceled event produced no member wool in world');
check(totals['minecraft:blue_wool'] === 1, 'only uncanceled blue wool entered world');
function recordKill(b) {
    b.setPos(-5,100,0);
    var row = {body:b, events:0, items:{}, cancel:false};
    lootRows.push(row);
    world.addFreshEntity(b);
    AutoJS.command('kill ' + String(b.uuid));
    check(row.events === 1, 'edge case has one public drop event');
    return row;
}
