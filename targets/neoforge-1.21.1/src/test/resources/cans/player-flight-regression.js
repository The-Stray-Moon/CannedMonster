var TF=Java.loadClass('cc.sighs.cannedmonster.fusion.FusionRuntime');
var FR=Java.loadClass('cc.sighs.cannedmonster.fusion.FlightRules');
var TE=Java.loadClass('net.minecraft.world.entity.EntityType');
var TL=Java.loadClass('java.util.List');
var tp=AutoJS.player(),tw=AutoJS.level(),checks=[];
function check(name,value){checks.push({name:name,pass:!!value});if(!value)throw new Error(name);}
if(!tp.isAlive()||tp.isRemoved())throw new Error('Respawn the test player before running this suite');
while(!TF.facets(tp).isEmpty())TF.peel(tp);
tp.setNoGravity(false);
check('baseline gravity enabled',!tp.isNoGravity());
var ghast=TE.GHAST.create(tw);
check('ghast is structurally flying',FR.structurallyFlies(ghast));
check('ghast is treated as flying',FR.flies(ghast));
var vex=TE.VEX.create(tw);
check('vex is configured as extra flying',FR.flies(vex));
var cow=TE.COW.create(tw);
check('cow is not flying',!FR.flies(cow));
TF.attach(tp,TL.of(ghast));
check('ghast fusion grants no gravity',tp.isNoGravity());
TF.peel(tp);
check('ghast peel restores gravity',!tp.isNoGravity());
tp.setNoGravity(true);
TF.attach(tp,TL.of(vex));
check('vex fusion grants no gravity',tp.isNoGravity());
TF.peel(tp);
check('vex peel clears pre-existing no gravity',!tp.isNoGravity());
TF.attach(tp,TL.of(cow));
check('cow fusion keeps gravity',!tp.isNoGravity());
TF.peel(tp);
check('gravity remains enabled after cleanup',!tp.isNoGravity());
JSON.stringify({checks:checks});
