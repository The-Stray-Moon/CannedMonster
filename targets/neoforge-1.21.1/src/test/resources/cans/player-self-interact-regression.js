var FR=Java.loadClass('cc.sighs.cannedmonster.fusion.FusionRuntime');
var ET=Java.loadClass('net.minecraft.world.entity.EntityType');
var IS=Java.loadClass('net.minecraft.world.item.ItemStack');
var Items=Java.loadClass('net.minecraft.world.item.Items');
var Hand=Java.loadClass('net.minecraft.world.InteractionHand');
var p=AutoJS.player(), level=AutoJS.level(), checks=[];
function check(name,value){checks.push({name:name,pass:!!value});if(!value)throw new Error(name);}
if(!p.isAlive()||p.isRemoved())throw new Error('Respawn the test player before running this suite');
if(p.isPassenger())p.stopRiding();
var held=p.getItemInHand(Hand.MAIN_HAND);
var savedHealth=p.getHealth();
var before=FR.facets(p).size();
var golem=ET.IRON_GOLEM.create(level);
FR.prepend(p, golem);
check('golem becomes the first member', FR.facets(p).size()===before+1 && FR.facets(p).get(0)===golem);
check('golem stays out of the world', !golem.isAddedToLevel());
p.setHealth(1.0);
p.setItemInHand(Hand.MAIN_HAND, new IS(Items.IRON_INGOT, 2));
check('self interaction consumes the action', AutoJS.use());
check('player heals through the shared body', Math.abs(p.getHealth()-Math.min(p.getMaxHealth(),26.0))<1.0E-6);
check('iron ingot is consumed', p.getItemInHand(Hand.MAIN_HAND).getCount()===1);
check('golem reads the shared health', Math.abs(golem.getHealth()-p.getHealth())<1.0E-6);
p.setHealth(p.getMaxHealth());
check('full health leaves the ingot untouched', !AutoJS.use() && p.getItemInHand(Hand.MAIN_HAND).getCount()===1);
p.setHealth(1.0);
p.setItemInHand(Hand.MAIN_HAND, new IS(Items.APPLE, 1));
check('item use keeps priority over members', AutoJS.use() && p.isUsingItem() && Math.abs(p.getHealth()-1.0)<1.0E-6);
p.stopUsingItem();
FR.peel(p);
var donkey=ET.DONKEY.create(level);
donkey.setTamed(true);
FR.prepend(p, donkey);
p.setItemInHand(Hand.MAIN_HAND, new IS(Items.DONKEY_SPAWN_EGG, 1));
check('tamed donkey ride request does not self-mount', AutoJS.use()
    && p.getVehicle()===null && p.getPassengers().isEmpty() && p.getRootVehicle()===p);
check('donkey spawn egg is not consumed on air', p.getItemInHand(Hand.MAIN_HAND).getCount()===1);
FR.peel(p);
p.setItemInHand(Hand.MAIN_HAND, held);
p.setHealth(Math.min(savedHealth, p.getMaxHealth()));
check('peel removes the test members and restores the previous fusion', FR.facets(p).size()===before);
var result=JSON.stringify({checks:checks});
if(typeof console!=='undefined'&&console.info)console.info(result);
result;
