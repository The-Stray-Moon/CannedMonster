var InteractionEvent = 'net.neoforged.neoforge.event.entity.player.PlayerInteractEvent$EntityInteract';
var Hand = Java.loadClass('net.minecraft.world.InteractionHand');
var publicRow = {events: 0, effects: 0, cancel: false, targets: []};
var publicHost = createType('cow');
publicHost.setPos(originX, testY, originZ);
var publicSheep = createType('sheep');
var publicPig = createType('pig');
F.attach(publicHost, JList.of(publicSheep, publicPig));
world.addFreshEntity(publicHost);
NativeEvents.onEvent(InteractionEvent, function(event) {
    if (event.getTarget() !== publicHost) return;
    publicRow.events++;
    publicRow.targets.push(String(event.getTarget().getType()));
    event.getEntity().giveExperiencePoints(1);
    publicRow.effects++;
    if (publicRow.cancel) event.setCanceled(true);
});
AutoJS.command('gamemode survival @a');
player.setItemInHand(Hand.MAIN_HAND, AutoJS.stack('minecraft:stick', 1));
var first = player.interactOn(publicHost, Hand.MAIN_HAND);
if (publicRow.events !== 1 || publicRow.effects !== 1) throw new Error('PASS interaction repeated public side effects');
player.setItemInHand(Hand.MAIN_HAND, AutoJS.stack('minecraft:red_dye', 1));
var second = player.interactOn(publicHost, Hand.MAIN_HAND);
if (publicRow.events !== 2 || publicRow.effects !== 2 || String(publicSheep.getColor()) !== 'red') throw new Error('Typed item view or public event count regressed');
publicRow.cancel = true;
player.setItemInHand(Hand.MAIN_HAND, AutoJS.stack('minecraft:blue_dye', 1));
var third = player.interactOn(publicHost, Hand.MAIN_HAND);
if (publicRow.events !== 3 || publicRow.effects !== 3 || String(publicSheep.getColor()) !== 'red') throw new Error('Cancellation did not stop internal dispatch');
publicRow.cancel = false;
player.setItemInHand(Hand.MAIN_HAND, AutoJS.stack('minecraft:shears', 1));
player.interactOn(publicHost, Hand.MAIN_HAND);
if (publicRow.events !== 4 || publicRow.effects !== 4 || !publicSheep.isSheared()) throw new Error('Shearing or single public event failed');
AutoJS.command('gamemode creative @a');
publicHost.discard();
JSON.stringify({events: publicRow.events, sideEffects: publicRow.effects, first: String(first), dye: String(second), cancellation: String(third), targets: publicRow.targets, sheared: publicSheep.isSheared()});
